
-- ==========================================
-- SC COVOITURAGE - DATABASE SCHEMA
-- PostgreSQL
-- ==========================================

-- 1. CONDUCTEURS
CREATE TABLE conducteurs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    telephone VARCHAR(20) NOT NULL,
    numero_permis VARCHAR(100) NOT NULL UNIQUE
);


-- 2. PASSAGERS
CREATE TABLE passagers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    telephone VARCHAR(20) NOT NULL
);


-- 3. VEHICULES
CREATE TABLE vehicules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marque VARCHAR(100) NOT NULL,
    modele VARCHAR(100) NOT NULL,
    immatriculation VARCHAR(50) NOT NULL UNIQUE,
    couleur VARCHAR(50) NOT NULL,

    capacite INTEGER NOT NULL,

    conducteur_id BIGINT NOT NULL,

    CONSTRAINT chk_vehicule_capacite
        CHECK (capacite BETWEEN 1 AND 8),

    CONSTRAINT fk_vehicule_conducteur
        FOREIGN KEY (conducteur_id)
        REFERENCES conducteurs(id)
        ON DELETE RESTRICT,

    -- Nécessaire pour garantir que le véhicule
    -- appartient bien au conducteur du trajet.
    CONSTRAINT uk_vehicule_id_conducteur
        UNIQUE (id, conducteur_id)
);


-- 4. TRAJETS
CREATE TABLE trajets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    conducteur_id BIGINT NOT NULL,
    vehicule_id BIGINT NOT NULL,

    date_depart TIMESTAMPTZ NOT NULL,

    places_proposees INTEGER NOT NULL,

    statut VARCHAR(20) NOT NULL DEFAULT 'PUBLIE',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_trajet_places
        CHECK (places_proposees BETWEEN 1 AND 8),

    CONSTRAINT chk_trajet_statut
        CHECK (statut IN (
            'PUBLIE',
            'COMPLET',
            'TERMINE',
            'ANNULE'
        )),

    CONSTRAINT fk_trajet_conducteur
        FOREIGN KEY (conducteur_id)
        REFERENCES conducteurs(id)
        ON DELETE RESTRICT,

    -- Garantit que le véhicule utilisé
    -- appartient au conducteur du trajet.
    CONSTRAINT fk_trajet_vehicule_conducteur
        FOREIGN KEY (vehicule_id, conducteur_id)
        REFERENCES vehicules(id, conducteur_id)
        ON DELETE RESTRICT
);


-- 5. POINTS D'ARRET
CREATE TABLE points_arret (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    trajet_id BIGINT NOT NULL,

    ville VARCHAR(150) NOT NULL,

    ordre INTEGER NOT NULL,

    heure_passage TIMESTAMPTZ NOT NULL,

    prix_depuis_depart NUMERIC(10, 2) NOT NULL,

    CONSTRAINT chk_point_ordre
        CHECK (ordre >= 0),

    CONSTRAINT chk_point_prix
        CHECK (prix_depuis_depart >= 0),

    CONSTRAINT fk_point_trajet
        FOREIGN KEY (trajet_id)
        REFERENCES trajets(id)
        ON DELETE CASCADE,

    CONSTRAINT uk_point_trajet_ordre
        UNIQUE (trajet_id, ordre),

    -- Nécessaire pour les clés étrangères
    -- composites de la table reservations.
    CONSTRAINT uk_point_id_trajet
        UNIQUE (id, trajet_id)
);


-- Une ville ne peut apparaître qu'une fois
-- dans le parcours d'un même trajet.
CREATE UNIQUE INDEX idx_point_ville_unique
ON points_arret (trajet_id, LOWER(ville));


-- 6. RESERVATIONS
CREATE TABLE reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    trajet_id BIGINT NOT NULL,
    passager_id BIGINT NOT NULL,

    point_montee_id BIGINT NOT NULL,
    point_descente_id BIGINT NOT NULL,

    nombre_places INTEGER NOT NULL,

    montant_total NUMERIC(10, 2) NOT NULL,

    date_reservation TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    statut VARCHAR(20) NOT NULL DEFAULT 'CONFIRMEE',

    CONSTRAINT chk_reservation_places
        CHECK (nombre_places BETWEEN 1 AND 8),

    CONSTRAINT chk_reservation_montant
        CHECK (montant_total >= 0),

    CONSTRAINT chk_reservation_statut
        CHECK (statut IN (
            'CONFIRMEE',
            'ANNULEE'
        )),

    CONSTRAINT fk_reservation_trajet
        FOREIGN KEY (trajet_id)
        REFERENCES trajets(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_reservation_passager
        FOREIGN KEY (passager_id)
        REFERENCES passagers(id)
        ON DELETE RESTRICT,

    -- Le point de montée doit appartenir au trajet.
    CONSTRAINT fk_reservation_point_montee
        FOREIGN KEY (point_montee_id, trajet_id)
        REFERENCES points_arret(id, trajet_id)
        ON DELETE RESTRICT,

    -- Le point de descente doit appartenir au même trajet.
    CONSTRAINT fk_reservation_point_descente
        FOREIGN KEY (point_descente_id, trajet_id)
        REFERENCES points_arret(id, trajet_id)
        ON DELETE RESTRICT
);


-- Un passager ne peut avoir qu'une seule réservation
-- CONFIRMEE pour un même trajet.
CREATE UNIQUE INDEX idx_reservation_passager_trajet_active
ON reservations (passager_id, trajet_id)
WHERE statut = 'CONFIRMEE';


-- ==========================================
-- INDEXES POUR AMELIORER LES RECHERCHES
-- ==========================================

CREATE INDEX idx_vehicules_conducteur
ON vehicules (conducteur_id);

CREATE INDEX idx_trajets_conducteur
ON trajets (conducteur_id);

CREATE INDEX idx_trajets_vehicule
ON trajets (vehicule_id);

CREATE INDEX idx_trajets_date_statut
ON trajets (date_depart, statut);

CREATE INDEX idx_points_trajet_ordre
ON points_arret (trajet_id, ordre);

CREATE INDEX idx_reservations_trajet_statut
ON reservations (trajet_id, statut);

CREATE INDEX idx_reservations_passager
ON reservations (passager_id);

CREATE INDEX idx_reservations_point_montee
ON reservations (point_montee_id);

CREATE INDEX idx_reservations_point_descente
ON reservations (point_descente_id);
